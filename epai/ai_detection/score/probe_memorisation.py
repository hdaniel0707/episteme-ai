# Long enough to be unambiguous -- a 20-word prefix of a news story matches a
# thousand news stories, and the completion would be graded on genre rather
# than on memory -- and short enough to leave a continuation worth comparing.
DEFAULT_PREFIX_WORDS = 60

# The reference continuation is capped so that every row is graded over the
# same budget: an LCS F1 computed over 400 words is not comparable with one
# computed over 40, and without a cap the metric would track document length.
DEFAULT_CONTINUATION_WORDS = 120

# A row has to be able to supply both halves. Rows that cannot are skipped
# before any call is made, and counted in the plan so a corpus of short
# documents does not look like a corpus of failures.
DEFAULT_MIN_CONTINUATION_WORDS = 40

# Tokens of exact, consecutive agreement at which a completion stops being
# fluency and starts being recall. Ten is deliberately conservative: stock
# phrases ("on the other hand, it is important to") reach six or seven without
# anybody having memorised anything.
VERBATIM_RUN = 10

DEFAULT_SAMPLE = 120
DEFAULT_WORKERS = 4

REPORT_DIR = Path("results") / "llm_judge_memorisation"

PROBE_UNGUIDED = "unguided"
PROBE_GUIDED = "guided"
PROBES = (PROBE_UNGUIDED, PROBE_GUIDED)

# The instruction is the same in both arms except for the provenance sentence,
# so that the guided-minus-unguided delta is attributable to the hint and to
# nothing else about how the two were asked.
UNGUIDED_SYSTEM = """You are completing a document that you have seen before.

You will be given the opening of a text. Reproduce what comes next in it, exactly as it was written -- not a plausible continuation of your own, and not a summary or paraphrase.

Reply with the continuation only. No preamble, no quotation marks, no commentary, no explanation of what you are doing. If you do not remember the text, write your best reconstruction of the continuation and nothing else."""

GUIDED_SYSTEM = """You are completing a document that you have seen before.

{provenance}

You will be given the opening of that text. Reproduce what comes next in it, exactly as it was written -- not a plausible continuation of your own, and not a summary or paraphrase.

Reply with the continuation only. No preamble, no quotation marks, no commentary, no explanation of what you are doing. If you do not remember the text, write your best reconstruction of the continuation and nothing else."""

# What the guided arm is told. Only ever about the collection -- never about
# this row -- so it carries no information a model without prior exposure to
# the collection could use.
PROVENANCE_TEMPLATE = (
    "The excerpt below is taken from {source}. It is from the {domain} portion "
    "of that collection, and it is one of the {label}-written documents in it."
)

USER_TEMPLATE = "{prefix}"


# ---------------------------------------------------------------------------
# Text handling and the three metrics
# ---------------------------------------------------------------------------

_WORD = re.compile(r"[^\s]+")
_TOKEN = re.compile(r"[a-z0-9']+")


def split_document(
    text: str, prefix_words: int, continuation_words: int, min_continuation: int
) -> tuple[str, str] | None:
    """Cut a document into (prefix shown, continuation held back).

    Split on whitespace runs rather than on tokens, so the prefix handed to the
    model is a real span of the original document -- punctuation, casing and
    spacing intact. A model asked to continue detokenised text is being asked a
    different question, and an easier one to fail for reasons that have nothing
    to do with memory.

    Returns None when the document cannot supply a reference continuation of at
    least ``min_continuation`` words, which is a skip and not an error.
    """
    words = _WORD.findall(text or "")
    if len(words) < prefix_words + min_continuation:
        return None
    prefix = " ".join(words[:prefix_words])
    reference = " ".join(words[prefix_words : prefix_words + continuation_words])
    return prefix, reference


def strip_preamble(text: str) -> str:
    """Drop the wrapper a chat model puts around a completion it was asked for.

    "Sure, here is the continuation:", a fenced block, a pair of quotation
    marks. None of it is the model's answer, and all of it depresses every
    metric below by the same amount in both arms -- which sounds harmless until
    one arm produces more of it than the other.
    """
    body = text.strip()
    body = re.sub(r"^```[a-zA-Z]*\s*|\s*```$", "", body).strip()
    # A short opening line that ends in a colon is a preamble; a long one is
    # the answer starting with a colon in it, and must be kept.
    lines = body.split("\n")
    if len(lines) > 1 and lines[0].rstrip().endswith(":") and len(lines[0]) < 120:
        body = "\n".join(lines[1:]).strip()
    if len(body) > 1 and body[0] in "\"'“‘" and body[-1] in "\"'”’":
        body = body[1:-1].strip()
    return body


def tokens(text: str) -> list[str]:
    """Words, lowercased, punctuation dropped. What the two token metrics see."""
    return _TOKEN.findall((text or "").lower())


def lcs_length(a: list[str], b: list[str]) -> int:
    """Length of the longest common subsequence, two rolling rows of DP.

    Written out rather than approximated with difflib's matching blocks:
    difflib finds a non-crossing cover, which is at or below the true LCS by an
    amount that depends on the input, and a metric whose bias depends on the
    input is not a metric you can compare across two arms.
    """
    if not a or not b:
        return 0
    previous = [0] * (len(b) + 1)
    for token_a in a:
        current = [0] * (len(b) + 1)
        for j, token_b in enumerate(b, start=1):
            current[j] = (
                previous[j - 1] + 1 if token_a == token_b
                else max(previous[j], current[j - 1])
            )
        previous = current
    return previous[-1]


def overlap_metrics(reference: str, hypothesis: str) -> dict[str, float]:
    """The three numbers, for one completion against its true continuation."""
    ref_tokens = tokens(reference)
    hyp_tokens = tokens(hypothesis)
    if not ref_tokens or not hyp_tokens:
        return {"lcs_f1": 0.0, "longest_run": 0, "char_ratio": 0.0}

    lcs = lcs_length(ref_tokens, hyp_tokens)
    # autojunk off: it treats any element in more than 1% of a >200-element
    # sequence as noise, which for word tokens means "the" and "of" -- exactly
    # the glue that holds a verbatim run together.
    matcher = difflib.SequenceMatcher(None, ref_tokens, hyp_tokens, autojunk=False)
    run = matcher.find_longest_match(0, len(ref_tokens), 0, len(hyp_tokens)).size
    chars = difflib.SequenceMatcher(
        None, reference.strip(), hypothesis.strip(), autojunk=False
    ).ratio()
    return {
        "lcs_f1": 2.0 * lcs / (len(ref_tokens) + len(hyp_tokens)),
        "longest_run": int(run),
        "char_ratio": float(chars),
    }


