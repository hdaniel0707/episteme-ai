"""Does the judge already know these documents? A verbatim-continuation probe.

THE WORRY, AND WHY IT HAS A DIRECTION
-------------------------------------
The judge columns say the API models separate human from machine text well
in-domain. There is a boring explanation that has to be ruled out before an
interesting one is believed: the judge may not be reading style at all, it may
be *recognising* the human documents because it was trained on them.

That worry is not symmetric, which is what makes it testable. In every corpus
here the two halves have completely different provenance:

    human half      Public, old, and heavily mirrored. Ghostbuster's `essay`
                    rows are IvyPanda student essays, `wp` is reddit
                    WritingPrompts, `reuter` is Reuters newswire. All of it was
                    on the open web years before any of these judges were
                    trained.
    machine half    Generated by us, recently, from prompts in this repo. It
                    cannot be in anybody's pretraining set.

So memorisation can only push one way: toward calling remembered human text
human. That is exactly the direction of the in-domain result, and it is why the
question is worth an experiment rather than a caveat.

WHAT THIS SCRIPT DOES
---------------------
For a sample of rows it cuts the document at `--prefix-words`, sends the model
the prefix and asks it to continue, and measures how close the continuation is
to the words that actually followed. Two prompts per row:

``unguided``
    "Continue this text." No hint about where the text came from.
``guided``
    The same, plus the name of the corpus and the domain the row is from -- the
    guided/unguided contrast of Golchin & Surdeanu (2023). The hint contains no
    information about *this document*, only about the collection, so it cannot
    help a model that has not seen the collection. A model that completes much
    better once told the dataset name has instance-level memory of it.

Three numbers per completion, all computed here with no extra dependency:

``lcs_f1``
    Token-level longest common subsequence, as F1 against the true
    continuation. The fuzzy one: catches "said roughly the same thing".
``longest_run``
    The longest run of *identical consecutive tokens* shared with the true
    continuation. The sharp one, and the one to believe. Fluency gets you
    paraphrase; it does not get you fifteen tokens in a row.
``char_ratio``
    difflib's similarity over the raw characters. A cross-check on the two
    above that is not tokenisation-dependent.

READ THE MACHINE ROWS AS THE CONTROL, CAREFULLY
-----------------------------------------------
Machine rows cannot be memorised, so they are the floor -- but they are not a
*neutral* floor. Model-written prose is more predictable than human prose, so a
model continuing it scores higher on `lcs_f1` than it would on human text of
equal novelty, with no memory involved at all. Expect the fuzzy metric to
favour the machine rows and do not read that as evidence of anything.

`longest_run` is much less exposed to this, and the guided-minus-unguided delta
is not exposed to it at all: it is the same documents both ways, and the only
thing that changed is whether the model was told the corpus name. That delta,
on human rows, is the number this script exists to produce.

BEFORE YOU SPEND ANYTHING ON THIS
---------------------------------
There is a free version of the same question already sitting in the parquets.
Three judges from two vendors plus a local 14B have scored every row, so:
compare per-domain accuracy *on human rows only* across
`llm_judge_score_gpt56luna_v3`, `llm_judge_score_sonnet5_v3` and
`llm_judge_score_qwen3_14b_v3`. One model's memorisation does not replicate
across vendors. If the human-row advantage is the same size everywhere, it is
more likely a real stylistic cue -- with the honest caveat that overlapping
pretraining corpora would also produce that, which is what this script is for.

WHAT IT DOES NOT TOUCH
----------------------
The Parquet. It is opened read-only and never written back: no column is added,
no score is changed. Everything produced lands under
``results/llm_judge_memorisation/<parquet>+<model>/``.

Run:
    uv run python epai/ai_detection/score/probe_memorisation.py \
        data/parquet/ghostbuster_gpt56luna.parquet \
        --guided-name "the Ghostbuster AI-text-detection benchmark (Verma et al., 2023)"

    # a first look, cheap
    uv run python epai/ai_detection/score/probe_memorisation.py \
        data/parquet/ghostbuster_gpt56luna.parquet --sample 40

    # the local judge, on one card
    uv run python epai/ai_detection/score/probe_memorisation.py \
        data/parquet/ghostbuster_gpt56luna.parquet \
        --model qwen3-14b --gpu 0 --cpu-threads 16

A natural extension, deliberately not built here: ask the model to *name* the
source of a document. It is cheap and it is suggestive, but it is self-report,
and a model will happily name a plausible source for text it has never seen. If
you want it, keep it in its own script and its own report -- do not let a
self-report number stand beside these measured ones.
"""

