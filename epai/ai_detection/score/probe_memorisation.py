# Asking the model to continue
# ---------------------------------------------------------------------------


def provenance_for(source: str, domain: str, generated_by: str) -> str:
    """The sentence the guided arm gets, and the unguided arm does not."""
    return PROVENANCE_TEMPLATE.format(
        source=source,
        domain=domain if domain and domain != "all" else "main",
        label="human" if generated_by == "human" else "machine",
    )


def system_for(probe: str, provenance: str) -> str:
    return (
        UNGUIDED_SYSTEM if probe == PROBE_UNGUIDED
        else GUIDED_SYSTEM.format(provenance=provenance)
    )


class ApiCompleter(ApiJudge):
    """Continuation over an API. Subclassed off the judge for its client only.

    Nothing here returns a score and nothing here reads one. The system prompt
    is per-call rather than per-instance, because the two arms differ by their
    system prompt and are otherwise the same call.
    """

    def __init__(self, spec: JudgeModel, max_tokens: int) -> None:
        # The prompt version is irrelevant here and only satisfies the base
        # class: `system_prompt` overrides it, and every call overrides that in
        # turn, since the arm is what decides the system prompt.
        super().__init__(spec, prompt_id=DEFAULT_PROMPT, mode=MODE_PARSED,
                         system_prompt=UNGUIDED_SYSTEM)
        self.max_tokens = max_tokens
        self._no_token_cap = False

    def complete(self, prefix: str, system: str) -> str:
        if self.provider == "openai":
            return self._complete_openai(prefix, system)
        if self.provider == "anthropic":
            return self._complete_anthropic(prefix, system)
        return self._complete_gemini(prefix, system)

    def _complete_openai(self, prefix: str, system: str) -> str:
        messages = [
            {"role": "system", "content": system},
            {"role": "user", "content": USER_TEMPLATE.format(prefix=prefix)},
        ]
        # No temperature: as in the scoring path, the reasoning-capable models
        # reject anything but the default. `max_completion_tokens` rather than
        # `max_tokens` for the same reason -- and if a model rejects even that,
        # the cap is dropped once and the run continues uncapped rather than
        # failing every row. The reference is capped anyway, so an uncapped
        # completion costs tokens, not correctness.
        kwargs = {} if self._no_token_cap else {
            "max_completion_tokens": self.max_tokens
        }
        try:
            response = self._client.chat.completions.create(
                model=self.model_id, messages=messages, **kwargs
            )
        except TypeError:
            self._no_token_cap = True
            response = self._client.chat.completions.create(
                model=self.model_id, messages=messages
            )
        content = response.choices[0].message.content
        if not content:
            raise ValueError("model returned an empty completion")
        return content

    def _complete_anthropic(self, prefix: str, system: str) -> str:
        response = self._client.messages.create(
            model=self.model_id,
            max_tokens=self.max_tokens,
            temperature=0.0,
            system=system,
            messages=[{"role": "user", "content": USER_TEMPLATE.format(prefix=prefix)}],
        )
        parts = [b.text for b in response.content if getattr(b, "type", "") == "text"]
        if not parts:
            raise ValueError("model returned an empty completion")
        return "\n".join(parts)

    def _complete_gemini(self, prefix: str, system: str) -> str:
        from google.genai import types

        response = self._client.models.generate_content(
            model=self.model_id,
            contents=USER_TEMPLATE.format(prefix=prefix),
            config=types.GenerateContentConfig(
                system_instruction=system,
                temperature=0.0,
                max_output_tokens=self.max_tokens,
            ),
        )
        if not response.text:
            raise ValueError("model returned an empty completion")
        return response.text


class LocalCompleter(LocalJudge):
    """Continuation on the GPU, a batch at a time.

    Inherits the loading, the chat template probing and the left-padded
    batching from LocalJudge. `_render` is overridden because the judge wraps
    its input in `<document>` tags: correct for a document being judged, wrong
    for a prefix being continued, where the tags would invite the model to
    close them instead of writing the next sentence.
    """

    def __init__(
        self,
        spec: JudgeModel,
        max_new_tokens: int,
        device: str = DEFAULT_DEVICE,
        dtype: str = DEFAULT_DTYPE,
        cpu_threads: int | None = None,
    ) -> None:
        super().__init__(
            spec,
            prompt_id=DEFAULT_PROMPT,
            mode=MODE_PARSED,
            device=device,
            dtype=dtype,
            # 0: the prefix is already short by construction, and truncating it
            # would silently change the question.
            max_doc_tokens=0,
            system_prompt=UNGUIDED_SYSTEM,
            cpu_threads=cpu_threads,
        )
        self.max_new_tokens = max_new_tokens

    def _render(self, text: str) -> str:  # type: ignore[override]
        user = USER_TEMPLATE.format(prefix=text)
        if self._supports_system:
            messages = [
                {"role": "system", "content": self.system_prompt},
                {"role": "user", "content": user},
            ]
        else:
            messages = [{"role": "user", "content": f"{self.system_prompt}\n\n{user}"}]
        kwargs = {"tokenize": False, "add_generation_prompt": True}
        try:
            return self.tokenizer.apply_chat_template(
                messages, enable_thinking=False, **kwargs
            )
        except TypeError:
            return self.tokenizer.apply_chat_template(messages, **kwargs)

    def complete_batch(self, prefixes: list[str], systems: list[str]) -> list[str]:
        # One system prompt per row, so a batch may mix the two arms. The
        # prompt is set, rendered and restored around the encode rather than
        # threaded through _render's signature, which the base class owns.
        torch = self._torch
        rendered = []
        original = self.system_prompt
        try:
            for prefix, system in zip(prefixes, systems):
                self.system_prompt = system
                rendered.append(self._render(prefix))
        finally:
            self.system_prompt = original
        encoded = self.tokenizer(
            rendered, return_tensors="pt", padding=True, add_special_tokens=False
        )
        encoded = {
            key: encoded[key].to(self.model.device)
            for key in ("input_ids", "attention_mask")
            if key in encoded
        }
        with torch.inference_mode():
            out = self.model.generate(
                **encoded,
                max_new_tokens=self.max_new_tokens,
                do_sample=False,
                pad_token_id=self.tokenizer.pad_token_id,
            )
        return self.tokenizer.batch_decode(
            out[:, encoded["input_ids"].shape[1] :], skip_special_tokens=True
        )


def build_completer(spec: JudgeModel, max_tokens: int, args):
    if spec.is_local:
        return LocalCompleter(
            spec,
            max_new_tokens=max_tokens,
            device=args.device,
            dtype=dtype_for(spec, args.dtype),
            cpu_threads=args.cpu_threads,
        )
    return ApiCompleter(spec, max_tokens=max_tokens)


