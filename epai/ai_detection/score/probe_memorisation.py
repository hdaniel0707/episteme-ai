@dataclass
class Task:
    """One (row, arm) pair: everything a call and its scoring need."""

    position: int
    probe: str
    prefix: str
    reference: str
    system: str
    domain: str
    generated_by: str


@dataclass
class Outcome:
    """What came back for one task."""

    task: Task
    completion: str = ""
    metrics: dict = field(default_factory=dict)
    error: str | None = None


def run_task(completer, task: Task, retries: int) -> Outcome:
    last_error = "unknown error"
    for attempt in range(retries + 1):
        try:
            raw = completer.complete(task.prefix, task.system)
            body = strip_preamble(raw)
            return Outcome(task=task, completion=body,
                           metrics=overlap_metrics(task.reference, body))
        except Exception as exc:
            last_error = f"{type(exc).__name__}: {exc}"
            if attempt == retries:
                break
            delay = completer.backoff(attempt)
            if delay:
                time.sleep(delay)
    return Outcome(task=task, error=last_error)


def run_task_batch(completer, batch: list[Task], retries: int) -> list[Outcome]:
    """A batch in one generate call, falling back to one at a time."""
    try:
        completions = completer.complete_batch(
            [t.prefix for t in batch], [t.system for t in batch]
        )
        out = []
        for task, raw in zip(batch, completions):
            body = strip_preamble(raw)
            out.append(Outcome(task=task, completion=body,
                               metrics=overlap_metrics(task.reference, body)))
        return out
    except Exception as exc:
        tqdm.write(f"  batch of {len(batch)} failed ({type(exc).__name__}: {exc}); "
                   "retrying one at a time")
        results = []
        for task in batch:
            try:
                raw = completer.complete_batch([task.prefix], [task.system])[0]
                body = strip_preamble(raw)
                results.append(Outcome(task=task, completion=body,
                                       metrics=overlap_metrics(task.reference, body)))
            except Exception as inner:
                results.append(Outcome(task=task,
                                       error=f"{type(inner).__name__}: {inner}"))
        return results


