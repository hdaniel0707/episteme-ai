def print_plan(args, spec: JudgeModel, tasks: list[Task], too_short: int,
               n_rows: int, source: str, max_tokens: int) -> None:
    rows = len({t.position for t in tasks})
    cells: dict[str, int] = {}
    for task in tasks:
        if task.probe == args.probes[0]:
            key = f"{task.domain} | {task.generated_by}"
            cells[key] = cells.get(key, 0) + 1
    print("=" * 78)
    print("Parquet  (read-only — this script never writes to it)")
    print(f"  file           : {args.parquet}")
    print(f"  rows           : {n_rows}")
    print(f"  too short      : {too_short}  (fewer than "
          f"{args.prefix_words}+{args.min_continuation} words)")
    print("Probe")
    print(f"  model          : {spec.key}  ({spec.model})")
    print(f"  arms           : {', '.join(args.probes)}")
    print(f"  guided name    : {source}")
    print(f"  cut            : {args.prefix_words} words shown, "
          f"{args.continuation_words} held back")
    print(f"  generation cap : {max_tokens} tokens")
    if spec.is_local:
        print(f"  device         : {args.device} "
              f"({dtype_for(spec, args.dtype)}), batch {args.batch_size}")
        print(f"  gpu            : "
              f"{args.gpu if args.gpu is not None else 'all visible (unset)'}")
    print("Sample")
    for key, count in sorted(cells.items()):
        print(f"    {key:<28}: {count}")
    print(f"  rows           : {rows}")
    print(f"  calls          : {len(tasks)}  ({len(args.probes)} per row)")
    print("=" * 78)


def main() -> None:
    args = parse_args()
    # Before blocking_reason, which imports torch to ask about CUDA.
    apply_runtime_limits(args)
    spec = resolve_model(args.model, None)
    source = args.guided_name or args.parquet.stem
    max_tokens = args.max_tokens or int(args.continuation_words * 2.2) + 32
    stem = f"{args.parquet.stem}+{spec.column}"

    blocked = blocking_reason(spec, args.device)
    if blocked:
        raise SystemExit(f"Cannot run probe with {spec.key!r}: {blocked}.")

    df = load_parquet(args.parquet)
    eligible = check_parquet(df, args.text_col, args.parquet)
    allowed = resolve_generated_by(args.generated_by)
    eligible = apply_generated_by(
        df, eligible, allowed, args.generated_by is not None, args.parquet
    )

    tasks, too_short = build_tasks(df, eligible, args, source)
    if not tasks:
        print("No rows long enough to probe — nothing to do.")
        return

    print_plan(args, spec, tasks, too_short, len(df), source, max_tokens)
    print()
    if spec.is_local:
        print(f"NOTE  {len(tasks)} completion(s) will be generated on {args.device}.")
    else:
        print(f"NOTE  this is a billed API call: {len(tasks)} completion(s).")
    if not args.yes:
        answer = input("Proceed? Type 'yes': ").strip().lower()
        if answer != "yes":
            print("Aborted — nothing was called.")
            return

    completer = build_completer(spec, max_tokens, args)
    outcomes: list[Outcome] = []
    failures: list[str] = []
    started = time.perf_counter()

    try:
        if spec.is_local:
            size = max(1, args.batch_size)
            batches = [tasks[i : i + size] for i in range(0, len(tasks), size)]
            with tqdm(total=len(tasks), desc=f"Completing ({spec.key})",
                      unit="call") as bar:
                for batch in batches:
                    for outcome in run_task_batch(completer, batch, args.retries):
                        outcomes.append(outcome)
                        if outcome.error:
                            failures.append(outcome.error)
                    bar.update(len(batch))
        else:
            pool = ThreadPoolExecutor(max_workers=max(1, args.workers))
            try:
                futures = [
                    pool.submit(run_task, completer, task, args.retries)
                    for task in tasks
                ]
                for future in tqdm(as_completed(futures), total=len(futures),
                                   desc=f"Completing ({spec.key})", unit="call"):
                    outcome = future.result()
                    outcomes.append(outcome)
                    if outcome.error:
                        failures.append(outcome.error)
            finally:
                pool.shutdown(wait=False, cancel_futures=True)
    except KeyboardInterrupt:
        print("\nInterrupted — summarising what came back.")

    seconds = time.perf_counter() - started
    print()
    print("=" * 78)
    print(f"  completed : {len(outcomes) - len(failures)} of {len(tasks)} "
          f"in {seconds:.1f}s")
    print(f"  failed    : {len(failures)}")
    if failures:
        by_message: dict[str, int] = {}
        for message in failures:
            by_message[message] = by_message.get(message, 0) + 1
        for message, count in sorted(by_message.items(), key=lambda kv: -kv[1])[:5]:
            print(f"    {count:>5}x  {message[:100]}")
    print("=" * 78)
    print()

    frame = rows_frame(outcomes)
    out = Tee()
    summary = summarise(frame, out, args.verbatim_run)
    directory = save_report(out, args.report_dir, stem, frame, summary)
    print(f"\nReport → {directory}")


if __name__ == "__main__":
    main()
