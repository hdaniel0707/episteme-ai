def build_tasks(
    df: pd.DataFrame, eligible: np.ndarray, args, source: str
) -> tuple[list[Task], int]:
    """The sampled rows, expanded into one task per arm.

    Sampling is round-robin across `domain` x `generated_by` -- the same strata
    the scoring and explaining runs use -- because the comparison this script
    reports is *between* those cells. A sample that is 80% one domain cannot
    say whether the effect is a property of the corpus or of that domain.

    Rows too short to yield a reference continuation are dropped before the
    sample is drawn, not after, so `--sample 120` is 120 usable rows.
    """
    domains = (
        df[DOMAIN_COL].astype(str).to_numpy() if DOMAIN_COL in df.columns
        else np.array(["all"] * len(df))
    )
    generators = (
        df[GENERATED_BY_COL].astype(str).to_numpy() if GENERATED_BY_COL in df.columns
        else np.array(["all"] * len(df))
    )

    # The column once, not one .iloc per row: this loop visits every eligible
    # row in the file to find out which are long enough, and on a 6000-row
    # corpus per-row indexing is the slowest thing in the script.
    texts = df[args.text_col].astype(str).to_numpy()

    usable: list[int] = []
    splits: dict[int, tuple[str, str]] = {}
    for pos in np.flatnonzero(eligible):
        pos = int(pos)
        cut = split_document(
            texts[pos],
            args.prefix_words, args.continuation_words, args.min_continuation,
        )
        if cut is not None:
            usable.append(pos)
            splits[pos] = cut
    too_short = int(eligible.sum()) - len(usable)

    labels = strata(df)
    chosen = take_round_robin(usable, labels, args.sample)

    tasks: list[Task] = []
    for pos in chosen:
        prefix, reference = splits[pos]
        provenance = provenance_for(source, domains[pos], generators[pos])
        for probe in args.probes:
            tasks.append(Task(
                position=pos, probe=probe, prefix=prefix, reference=reference,
                system=system_for(probe, provenance),
                domain=domains[pos], generated_by=generators[pos],
            ))
    return tasks, too_short


