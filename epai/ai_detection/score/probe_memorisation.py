class Tee:
    """Collect printed lines so they can be echoed to stdout and a log file."""

    def __init__(self) -> None:
        self._lines: list[str] = []

    def print(self, line: str = "") -> None:
        print(line)
        self._lines.append(line)

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(self._lines) + "\n")


def rows_frame(outcomes: list[Outcome]) -> pd.DataFrame:
    """Every scored completion, one row each. The artefact to go back to."""
    return pd.DataFrame([
        {
            "row": o.task.position,
            "probe": o.task.probe,
            "domain": o.task.domain,
            "generated_by": o.task.generated_by,
            "reference_words": len(o.task.reference.split()),
            "lcs_f1": round(o.metrics.get("lcs_f1", float("nan")), 4),
            "longest_run": o.metrics.get("longest_run", -1),
            "char_ratio": round(o.metrics.get("char_ratio", float("nan")), 4),
            "prefix": o.task.prefix,
            "reference": o.task.reference,
            "completion": o.completion,
        }
        for o in outcomes if o.error is None
    ])


def summarise(frame: pd.DataFrame, out: Tee, verbatim_run: int) -> pd.DataFrame:
    """Print the per-cell table and the two contrasts that carry the answer."""
    if frame.empty:
        out.print("No completions scored — nothing to summarise.")
        return pd.DataFrame()

    frame = frame.copy()
    frame["class"] = np.where(frame["generated_by"] == "human", "human", "machine")
    frame["verbatim"] = frame["longest_run"] >= verbatim_run

    out.print("=" * 86)
    out.print(f"Continuation overlap  (verbatim run threshold: {verbatim_run} tokens)")
    out.print("-" * 86)
    out.print(f"{'domain':<12}{'class':<9}{'probe':<10}{'n':>5}"
              f"{'lcs_f1':>10}{'run':>8}{'>=run':>9}{'char':>9}")
    out.print("-" * 86)

    grouped = frame.groupby(["domain", "class", "probe"], sort=True)
    records: list[dict] = []
    for (domain, klass, probe), block in grouped:
        record = {
            "domain": domain, "class": klass, "probe": probe, "n": len(block),
            "lcs_f1": round(float(block["lcs_f1"].mean()), 4),
            "longest_run": round(float(block["longest_run"].mean()), 2),
            "pct_verbatim": round(100.0 * float(block["verbatim"].mean()), 1),
            "char_ratio": round(float(block["char_ratio"].mean()), 4),
        }
        records.append(record)
        out.print(f"{domain:<12}{klass:<9}{probe:<10}{record['n']:>5}"
                  f"{record['lcs_f1']:>10.3f}{record['longest_run']:>8.1f}"
                  f"{record['pct_verbatim']:>8.0f}%{record['char_ratio']:>9.3f}")

    out.print("=" * 86)
    out.print("The two contrasts")
    out.print("-" * 86)

    # 1. Human against machine, unguided. The floor comparison -- and the one
    #    that has to be read with the predictability caveat in the docstring,
    #    which is why `run` is printed beside `lcs_f1` and not instead of it.
    unguided = frame[frame["probe"] == PROBE_UNGUIDED]
    if not unguided.empty and unguided["class"].nunique() == 2:
        human = unguided[unguided["class"] == "human"]
        machine = unguided[unguided["class"] == "machine"]
        out.print("  human vs machine, unguided (machine rows cannot be memorised):")
        out.print(f"    lcs_f1      human {human['lcs_f1'].mean():.3f}   "
                  f"machine {machine['lcs_f1'].mean():.3f}   "
                  f"(fuzzy — expect machine to lead, it is more predictable)")
        out.print(f"    longest_run human {human['longest_run'].mean():.1f}   "
                  f"machine {machine['longest_run'].mean():.1f}   "
                  f"(the one to believe)")
        out.print(f"    >= {verbatim_run} tokens human "
                  f"{100 * human['verbatim'].mean():.0f}%   "
                  f"machine {100 * machine['verbatim'].mean():.0f}%")
    else:
        out.print("  human vs machine: needs both classes in the sample — skipped.")

    # 2. Guided minus unguided, on human rows. Same documents, same prompt but
    #    for the provenance sentence, so predictability cancels and what is
    #    left is whether naming the corpus unlocked anything.
    out.print()
    if set(PROBES).issubset(set(frame["probe"].unique())):
        for klass in ("human", "machine"):
            block = frame[frame["class"] == klass]
            if block.empty:
                continue
            wide = block.pivot_table(
                index="row", columns="probe",
                values=["lcs_f1", "longest_run"], aggfunc="mean",
            ).dropna()
            if wide.empty:
                continue
            d_f1 = (wide[("lcs_f1", PROBE_GUIDED)]
                    - wide[("lcs_f1", PROBE_UNGUIDED)])
            d_run = (wide[("longest_run", PROBE_GUIDED)]
                     - wide[("longest_run", PROBE_UNGUIDED)])
            out.print(f"  guided minus unguided, {klass} rows (n={len(wide)}), "
                      "paired on the same documents:")
            out.print(f"    lcs_f1      {d_f1.mean():+.3f}  "
                      f"(sd {d_f1.std(ddof=1):.3f})  "
                      f"improved on {100 * (d_f1 > 0).mean():.0f}% of rows")
            out.print(f"    longest_run {d_run.mean():+.2f}  "
                      f"(sd {d_run.std(ddof=1):.2f})  "
                      f"improved on {100 * (d_run > 0).mean():.0f}% of rows")
        out.print()
        out.print("  A delta near zero on both classes is the clean result: naming")
        out.print("  the corpus bought nothing, so there is no instance-level memory")
        out.print("  of it. A clear positive delta on human rows only is the finding")
        out.print("  this script exists to detect.")
    else:
        out.print("  guided minus unguided: needs --probes unguided guided — skipped.")
    out.print("=" * 86)
    return pd.DataFrame(records)


def save_report(
    out: Tee, report_dir: Path, stem: str, frame: pd.DataFrame, summary: pd.DataFrame
) -> Path:
    directory = report_dir / stem
    directory.mkdir(parents=True, exist_ok=True)
    out.save(directory / "memorisation_summary.log")
    if not frame.empty:
        frame.to_csv(directory / "completions.csv", index=False)
    if not summary.empty:
        summary.to_csv(directory / "memorisation_summary.csv", index=False)
    return directory


