def _openai_call(client, model_id, system, doc, top_n):
    resp = client.responses.create(
        model=model_id,
        instructions=system,
        input=USER_TEMPLATE.format(text=doc),
        include=["message.output_text.logprobs"],
        top_logprobs=top_n,
        reasoning={"effort": "none"},
        max_output_tokens=16,
    )
    for item in getattr(resp, "output", []) or []:
        if getattr(item, "type", None) == "message":
            for part in getattr(item, "content", []) or []:
                if getattr(part, "type", None) == "output_text":
                    print(f"      output_text : {getattr(part, 'text', None)!r}")
                    return getattr(part, "logprobs", None)
    print("      no output_text part in the response")
    return None


def _genai4science_call(client, model_id, system, doc, top_n):
    from epai.utils.env_utils import qwen3_thinking_off
    messages = qwen3_thinking_off(model_id, [
        {"role": "system", "content": system},
        {"role": "user", "content": USER_TEMPLATE.format(text=doc)},
    ])
    resp = client.chat.completions.create(
        model=model_id, messages=messages, max_tokens=1, temperature=0,
        logprobs=True, top_logprobs=min(top_n, 20),
    )
    ch = resp.choices[0]
    print(f"      content : {ch.message.content!r}")
    lp = getattr(ch, "logprobs", None)
    return getattr(lp, "content", None) if lp is not None else None


def _build_client(provider):
    from openai import OpenAI
    if provider == "openai":
        return OpenAI()
    if provider == "genai4science":
        from epai.utils.env_utils import genai4science_endpoint
        base_url, key_env = genai4science_endpoint()
        key = os.environ.get(key_env)
        if not key:
            raise SystemExit(f"{key_env} is not set -- see .env")
        return OpenAI(base_url=base_url, api_key=key)
    raise SystemExit(f"no logprob path for provider {provider!r} "
                     "(anthropic / gemini do not return token logprobs on a chat answer)")


def _sample_rows(path, n, text_col):
    import pyarrow.parquet as pq
    cols = [text_col] + (["generated_by"] if "generated_by"
                         in pq.read_schema(path).names else [])
    t = pq.read_table(path, columns=cols).to_pydict()
    texts = t[text_col]
    if "generated_by" in t:
        gen = [str(g) for g in t["generated_by"]]
        hu = [texts[i] for i, g in enumerate(gen) if g == "human"][: n // 2]
        ma = [texts[i] for i, g in enumerate(gen) if g != "human"][: n - len(hu)]
        return {f"human[{i}]": x for i, x in enumerate(hu)} | \
               {f"machine[{i}]": x for i, x in enumerate(ma)}
    return {f"row[{i}]": texts[i] for i in range(min(n, len(texts)))}


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--model", default="gpt56luna", choices=list(MODELS),
                    help="judge alias from add_llm_judge_scores.MODELS")
    ap.add_argument("--scale", type=int, default=5, choices=sorted(_SCALE_WORDS),
                    help="number of rating levels (default 5)")
    ap.add_argument("--prompt", default="v3",
                    help="prompt id whose evidence half frames the judge (default v3)")
    ap.add_argument("--toy", action="store_true",
                    help="skip the real evidence half, use a one-line framing")
    ap.add_argument("--top-n", type=int, default=LOGPROB_API_TOP_N)
    ap.add_argument("--parquet", type=str, default=None,
                    help="sample rows to judge from this parquet instead of the toy docs")
    ap.add_argument("--n", type=int, default=6, help="rows to sample with --parquet")
    ap.add_argument("--text-col", default="text")
    args = ap.parse_args()

    try:
        from dotenv import load_dotenv
        load_dotenv()
    except Exception:
        pass

    spec = MODELS[args.model]
    if spec.provider == "openai" and not os.environ.get("OPENAI_API_KEY"):
        raise SystemExit("OPENAI_API_KEY is not set -- see .env")
    client = _build_client(spec.provider)

    if args.toy:
        system = ("You are a forensic linguist deciding whether a document was "
                  "written by a human or generated by a large language model.\n\n"
                  + _scale_block(args.scale))
    else:
        system = evidence_head(args.prompt) + "\n\n" + _scale_block(args.scale)

    docs = _sample_rows(args.parquet, args.n, args.text_col) if args.parquet else _DOCS

    print(f"model  : {args.model} -> {spec.model}  ({spec.provider})")
    print(f"scale  : {args.scale}-way  ({' '.join(_LETTERS[:args.scale])} = "
          f"machine .. human)")
    print(f"prompt : {'toy' if args.toy else args.prompt} evidence + scale answer block")
    print(f"docs   : {len(docs)}  ({'sampled from ' + args.parquet if args.parquet else 'toy'})")
    print("=" * 74)
    print("\nSCALE ANSWER BLOCK:\n" + _scale_block(args.scale))
    print("=" * 74)

    caller = _openai_call if spec.provider == "openai" else _genai4science_call
    summ: list[dict] = []
    for name, doc in docs.items():
        print(f"\n-- {name}")
        try:
            lp = caller(client, spec.model, system, doc, args.top_n)
        except Exception as exc:  # noqa: BLE001 -- error text is the result
            print(f"      ERROR: {type(exc).__name__}: {exc}")
            continue
        # what a full run would persist per row instead of only the float:
        if lp:
            raw = [{"token": a.token, "logprob": round(a.logprob, 4)}
                   for a in (lp[0].top_logprobs or [])]
            print(f"      would store: {json.dumps(raw)[:300]}")
        r = _analyse(lp, args.scale)
        if r:
            r["doc"] = name
            summ.append(r)

    print(f"\n{'=' * 74}\nSUMMARY\n{'=' * 74}")
    for r in summ:
        print(f"  {r['doc']:<14} window={r['window']:<3} "
              f"on_scale={r.get('on_scale_mass', 0):.2f} "
              f"EV={r.get('expected_value', float('nan')):.3f} "
              f"collapsed={r.get('p_human_collapsed', float('nan')):.3f} "
              f"H={r.get('entropy', float('nan')):.2f} "
              f"{'SATURATED' if r.get('saturated') else ''}")
    graded = [r for r in summ if not r.get("saturated") and r.get("window", 0) >= 2]
    print(f"\n{len(graded)}/{len(summ)} document(s) gave a graded distribution "
          f"(>=2 letters in the window, no single letter > 98%).")
    print("If most are graded -> the N-way readout works for this model; pick a "
          "score function (expected_value is the usual choice) and wire a "
          "_score_*_scale path. If most are SATURATED even here -> the model is "
          "too peaked for any logprob readout; use it in --mode parsed.")


if __name__ == "__main__":
    main()
