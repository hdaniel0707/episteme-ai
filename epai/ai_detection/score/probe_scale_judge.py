r"""Capability probe: an N-level rating readout for the LLM judge.

The parsed judge (``llm_judge_score_*_v3``) writes a probability and it clumps on
round numbers. The two-word logprob judge (``_v3_lp``) reads
``P(human)/(P(human)+P(machine))`` off the answer token -- continuous where both
words sit in the returned window, but for a very confident judge the losing word
falls outside the window and the score rails to exactly 0 / 1. For an OpenAI
reasoning model (``gpt-5.6-luna``) the window comes back with a single token, so
the two-word ratio never engages at all.

This probe tries a different answer shape: the model picks one of N ordered
letters -- ``A`` = almost certainly machine ... ``E`` = almost certainly human --
and the score is read off the distribution over those N single-letter tokens.
N letters always fit inside a top-5 window, and even a confident model spreads
some mass to the neighbouring letter, so the read stays graded. Several
candidate score functions are printed for each document -- picking the one to
keep is the point of the probe, not decided here.

Nothing reads or writes a parquet unless ``--parquet`` is given, and then only to
sample a few rows to judge. This does not touch ``add_llm_judge_scores.py`` or
any existing mode.

PATHS
    openai        Responses API, ``reasoning={"effort":"none"}``,
                  ``include=["message.output_text.logprobs"]`` -- the only path
                  that returns logprobs for the GPT-5.x line.
    genai4science Chat Completions ``logprobs=True`` -- the ``_v3_lp`` path.
    anthropic / gemini   no token logprobs on a chat answer; skipped.

    uv run python epai/ai_detection/score/probe_scale_judge.py
    uv run python epai/ai_detection/score/probe_scale_judge.py --model gemma4-31b --scale 5
    uv run python epai/ai_detection/score/probe_scale_judge.py --parquet data/parquet/manugram_sci.parquet --n 8
    uv run python epai/ai_detection/score/probe_scale_judge.py --scale 7 --top-n 20
"""

from __future__ import annotations

import argparse
import json
import math
import os
import re

from epai.ai_detection.score.add_llm_judge_scores import (
    LOGPROB_API_TOP_N,
    MODELS,
    USER_TEMPLATE,
    evidence_head,
)

# A ..  z ; only N are used. Values are evenly spaced 0 (machine) .. 1 (human),
# to match the existing columns, which are all P(human).
_LETTERS = "ABCDEFGHIJ"

# Wording per level for the three sizes worth trying. machine -> human order.
_SCALE_WORDS = {
    3: ["machine-generated", "genuinely uncertain", "human-written"],
    5: ["almost certainly machine-generated", "probably machine-generated",
        "genuinely uncertain",
        "probably human-written", "almost certainly human-written"],
    7: ["almost certainly machine-generated", "probably machine-generated",
        "leaning machine-generated", "genuinely uncertain",
        "leaning human-written", "probably human-written",
        "almost certainly human-written"],
}

_DOCS = {
    "human-ish": (
        "honestly not sure why this took me three tries. the wiring diagram in "
        "the manual is wrong -- pin 2 and pin 5 are swapped -- and i only worked "
        "it out after the second fuse went."
    ),
    "machine-ish": (
        "In conclusion, the proposed framework offers a robust and scalable "
        "solution. By leveraging these key advantages, organizations can "
        "effectively navigate the evolving landscape and unlock significant "
        "value across multiple dimensions."
    ),
    "neutral": (
        "The committee reviewed the proposal and, after some deliberation, "
        "decided to postpone the vote until the next quarterly meeting."
    ),
}


def _scale_block(n: int) -> str:
    words = _SCALE_WORDS[n]
    lines = "\n".join(f"{_LETTERS[i]}  {w}" for i, w in enumerate(words))
    return (
        "ANSWER\n"
        "Answer with exactly one letter, and nothing else, rating how likely the "
        "document was generated by a large language model rather than written by "
        "a human:\n"
        f"{lines}\n"
        "No explanation, no punctuation. Judge each document on its own; do not "
        "assume any particular mix of human and machine documents."
    )


def _letter_of(token: str) -> str | None:
    """The bare letter a returned token stands for, or None. Handles ``A``,
    `` A``, ``a``, ``**A**``, ``A)``, ``A.`` ."""
    s = re.sub(r"[^A-Za-z]", "", token).upper()
    return s if len(s) == 1 and s in _LETTERS else None


def _analyse(lp_list, n: int) -> dict | None:
    """``lp_list`` items need ``.token`` and ``.top_logprobs`` (each ``.token`` /
    ``.logprob``). Prints the window and several candidate scores. Returns a
    small dict of the numbers, or None if there is nothing to read."""
    if not lp_list:
        print("      logprobs: NONE / empty -- not returned for this call")
        return None
    slot = lp_list[0]
    alts = slot.top_logprobs or []
    letters = list(_LETTERS[:n])
    values = [i / (n - 1) for i in range(n)]  # 0 .. 1

    print(f"      answer token 0 : {slot.token!r}  (letter {_letter_of(slot.token)})")
    print(f"      window ({len(alts)}):")
    bucket_p = {L: 0.0 for L in letters}
    off_scale = 0.0
    for a in alts:
        p = math.exp(a.logprob)
        L = _letter_of(a.token)
        tag = f"  -> {L}" if L in bucket_p else "  (off-scale)"
        print(f"        {a.token!r:<14} logprob={a.logprob:8.4f}  p={p:.4g}{tag}")
        if L in bucket_p:
            bucket_p[L] += p
        else:
            off_scale += p

    on_scale = sum(bucket_p.values())
    if on_scale <= 0:
        print("      -> no scale letter in the window; cannot score")
        return {"window": len(alts), "on_scale_mass": 0.0}

    norm = {L: bucket_p[L] / on_scale for L in letters}          # renormalised over A..N
    ev = sum(norm[L] * v for L, v in zip(letters, values))       # expected value
    mid = n // 2
    p_human = sum(norm[letters[i]] for i in range(mid + 1, n)) \
        + (0.5 * norm[letters[mid]] if n % 2 else 0.0)           # collapse to binary
    ent = -sum(pp * math.log(pp) for pp in norm.values() if pp > 0)
    argmax_L = max(letters, key=lambda L: norm[L])

    dist = "  ".join(f"{L}={norm[L]:.3f}" for L in letters)
    print(f"      on-scale mass  : {on_scale:.3f}   (off-scale {off_scale:.3f})")
    print(f"      distribution   : {dist}")
    print(f"      SCORES  expected_value={ev:.4f}   p_human_collapsed={p_human:.4f}"
          f"   argmax={argmax_L}({values[letters.index(argmax_L)]:.2f})"
          f"   entropy={ent:.3f}")
    saturated = max(norm.values()) > 0.98
    if saturated:
        print("      [SATURATED -- one letter holds >98% even on the N-way question]")
    return {"window": len(alts), "on_scale_mass": on_scale, "expected_value": ev,
            "p_human_collapsed": p_human, "entropy": ent, "argmax": argmax_L,
            "saturated": saturated}


