BASE_DIR = Path(__file__).resolve().parents[3]
PARQUET_DIR = BASE_DIR / "data" / "parquet"
WORKSPACE = PARQUET_DIR / "tmp" / "rebuttal"  # data/ is gitignored

CORE_STEMS = ["ghostbuster_orig", "manugram_gb", "manugram_sci", "manugram_aiscientist"]
HUMAN = "human"
SEED = 0

